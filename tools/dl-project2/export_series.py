"""DL Project 2 explainer: export small real-data excerpts for the scenes.

Reads temperatures-2026.pkl (read-only) and writes a tiny JS data module, so
the explainer scenes plot real Perth sequences instead of invented sine waves.
Nothing here is shown as a result; results always come from the notebook.

Run from Windows (CPU only, so it never competes for the GPU):
  MSYS_NO_PATHCONV=1 wsl.exe -d Ubuntu --cd "C:\\Users\\james\\Documents\\university\\cits5017\\cits5017-project-two" \
    -e env CUDA_VISIBLE_DEVICES=-1 TF_CPP_MIN_LOG_LEVEL=2 \
    /home/james/miniconda3/envs/tf-2.20-gpu/bin/python \
    /mnt/c/Users/james/Documents/personal-projects/wigfield-portfolio/tools/dl-project2/export_series.py \
    /mnt/c/Users/james/Documents/personal-projects/wigfield-portfolio/src/components/portal/modules/deep-learning/project2/data/series.js
"""
import json
import pickle
import sys

import numpy as np
import tensorflow as tf  # noqa: F401  (the pickle holds EagerTensors)

OUT = sys.argv[1]
with open("temperatures-2026.pkl", "rb") as f:
    train_seq, val_seq, test_seq = pickle.load(f)
tr, va, te = (np.asarray(t, dtype=np.float64) for t in (train_seq, val_seq, test_seq))


def r1(a):
    return np.round(np.asarray(a, dtype=np.float64), 1).tolist()


def overlap(seq):
    """True if window j+1 is window j shifted by one month (stride-1 windows)."""
    return bool(np.allclose(seq[1:, :-1], seq[:-1, 1:]))


def station(seq):
    """Rebuild the station's monthly record from stride-1 windows."""
    return np.concatenate([seq[0], seq[1:, -1]], axis=0)


out = {
    "source": "temperatures-2026.pkl",
    "shapes": {"train": list(tr.shape), "val": list(va.shape), "test": list(te.shape)},
    "overlap": {"val": overlap(va), "test": overlap(te), "train_first_pair": bool(np.allclose(tr[1, :-1], tr[0, 1:]))},
    "splitMeans": {
        k: {"min": round(float(v[..., 0].mean()), 2), "max": round(float(v[..., 1].mean()), 2)}
        for k, v in (("train", tr), ("val", va), ("test", te))
    },
    "range": {
        k: {
            "min": [round(float(v[..., 0].min()), 1), round(float(v[..., 0].max()), 1)],
            "max": [round(float(v[..., 1].min()), 1), round(float(v[..., 1].max()), 1)],
        }
        for k, v in (("train", tr), ("val", va), ("test", te))
    },
    # a handful of whole sequences, [month][min, max]
    # the notebook's own draws (section 4: train 566/1101/1474, val 182/56/86, test 240/257/220;
    # SHOW = test 95/259/140 in every model plot) plus a few fixed extras
    "trainSeqs": {str(i): r1(tr[i]) for i in (0, 500, 1000, 566, 1101, 1474)},
    "valSeqs": {str(i): r1(va[i]) for i in (0, 150, 182, 56, 86)},
    "testSeqs": {str(i): r1(te[i]) for i in (0, 1, 2, 150, 95, 259, 140, 240, 257, 220)},
}
if out["overlap"]["test"]:
    out["bickley"] = r1(station(te))
if out["overlap"]["val"]:
    out["swanbourne"] = r1(station(va))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* GENERATED by tools/dl-project2/export_series.py from temperatures-2026.pkl.\n")
    f.write("   Real data excerpts for scene drawing only; results come from the notebook. */\n")
    f.write("export const SERIES = ")
    json.dump(out, f, separators=(",", ":"))
    f.write(";\n")
print(json.dumps({k: out[k] for k in ("shapes", "overlap", "splitMeans", "range")}, indent=1))
print("bickley months:", len(out.get("bickley", [])), "swanbourne months:", len(out.get("swanbourne", [])))
