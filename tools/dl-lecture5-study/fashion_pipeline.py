import time
import urllib.request
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np  # noqa: E402
import tensorflow as tf  # noqa: E402

SEED = 42
BASE_URL = "https://storage.googleapis.com/tensorflow/tf-keras-datasets/"
FILES = [
    "train-labels-idx1-ubyte.gz",
    "train-images-idx3-ubyte.gz",
    "t10k-labels-idx1-ubyte.gz",
    "t10k-images-idx3-ubyte.gz",
]
CLASS_NAMES = ["T-shirt/top", "Trouser", "Pullover", "Dress", "Coat",
               "Sandal", "Shirt", "Sneaker", "Bag", "Ankle boot"]
N_VALID = 5000
EXPECTED_PARAMS = {"stacked_ae": 163_814, "tied_ae": 82_414,
                   "stacked_ae_1_by_1": 163_814}
SCRIPT_PATH = "tools/dl-lecture5-study/fashion_pipeline.py"
DISCLAIMER = "Generated by this page's own run; not the slides' figures."


# ---------------------------------------------------------------- data -----
def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch(data_dir):
    data_dir.mkdir(parents=True, exist_ok=True)
    hashes = {}
    for name in FILES:
        path = data_dir / name
        if not path.exists():
            print(f"downloading {BASE_URL + name}")
            tmp = path.with_suffix(".part")
            urllib.request.urlretrieve(BASE_URL + name, tmp)
            tmp.replace(path)
        hashes[name] = sha256(path)
        print(f"  {name}  sha256 {hashes[name]}")
    return hashes


def read_idx(path, magic, offset):
    with gzip.open(path, "rb") as f:
        raw = f.read()
    got = int.from_bytes(raw[:4], "big")
    if got != magic:
        sys.exit(f"{path}: IDX magic {got}, expected {magic}")
    # same parsing as keras.datasets.fashion_mnist.load_data()
    return np.frombuffer(raw, np.uint8, offset=offset)


def load_fashion(data_dir):
    y = read_idx(data_dir / FILES[0], 2049, 8)
    x = read_idx(data_dir / FILES[1], 2051, 16).reshape(len(y), 28, 28)
    if x.shape != (60000, 28, 28):
        sys.exit(f"unexpected training set shape {x.shape}")
    return x, y


# -------------------------------------------------------------- models -----
# Slide 20, verbatim (the "# ***" line is the lecturer's change to Geron's code).
class DenseTranspose(tf.keras.layers.Layer):
    def __init__(self, dense, activation=None, **kwargs):
        super().__init__(**kwargs)
        self.dense = dense
        self.activation = tf.keras.activations.get(activation)

    def build(self, batch_input_shape):
        self.biases = self.add_weight(
                        name="bias",
                        shape=[self.dense.input.shape[-1]],    # ***
                        initializer="zeros")
        super().build(batch_input_shape)

    def call(self, inputs):
        Z = tf.matmul(inputs, self.dense.weights[0], transpose_b=True)
        return self.activation(Z + self.biases)


def build_stacked():
    # Slide 12
    stacked_encoder = tf.keras.Sequential([
        tf.keras.layers.InputLayer(shape=[28, 28]),
        tf.keras.layers.Flatten(),
        tf.keras.layers.Dense(100, activation="relu"),
        tf.keras.layers.Dense(30, activation="relu"),
    ])
    stacked_decoder = tf.keras.Sequential([
        tf.keras.layers.Dense(100, activation="relu"),
        tf.keras.layers.Dense(28 * 28),
        tf.keras.layers.Reshape([28, 28])
    ])
    stacked_ae = tf.keras.Sequential([stacked_encoder, stacked_decoder])
    return stacked_encoder, stacked_ae


def build_tied():
    # Slides 20-21
    dense_1 = tf.keras.layers.Dense(100, activation="relu")
    dense_2 = tf.keras.layers.Dense(30, activation="relu")
    tied_encoder = tf.keras.Sequential([
        tf.keras.layers.InputLayer(shape=[28, 28]),
        tf.keras.layers.Flatten(),
        dense_1,
        dense_2
    ])
    tied_decoder = tf.keras.Sequential([
        DenseTranspose(dense_2, activation="relu"),
        DenseTranspose(dense_1),
        tf.keras.layers.Reshape([28, 28])
    ])
    tied_ae = tf.keras.Sequential([tied_encoder, tied_decoder])
    return tied_ae


PHASE_HISTORIES = []  # not on the slide: records each phase's history for export


def train_autoencoder(n_neurons, X_train, X_valid, n_epochs=10,
                      output_activation=None):
    # Slide 24 (only change: the fit history is kept for the export)
    n_inputs = X_train.shape[-1]
    encoder = tf.keras.layers.Dense(n_neurons, activation="relu")
    decoder = tf.keras.layers.Dense(n_inputs, activation=output_activation)
    autoencoder = tf.keras.Sequential([encoder, decoder])
    autoencoder.compile(loss="mse", optimizer="nadam")
    history = autoencoder.fit(X_train, X_train, epochs=n_epochs,
                              validation_data=(X_valid, X_valid), verbose=2)
    PHASE_HISTORIES.append(history.history)
    return encoder, decoder, encoder(X_train), encoder(X_valid)


def count_trainable(model):
    return int(sum(np.prod(w.shape) for w in model.trainable_weights))


def gate(name, model):
    total = model.count_params()
    trainable = count_trainable(model)
    want = EXPECTED_PARAMS[name]
    ok = total == want and trainable == want
    print(f"GATE {name}: count_params() = {total:,}  trainable = {trainable:,}  "
          f"expected {want:,}  -> {'PASS' if ok else 'FAIL'}")
    if not ok:
        sys.exit(f"parameter gate failed for {name}; nothing exported")
    return total


# ------------------------------------------------------------- helpers -----
def sig4(v):
    return float(f"{float(v):.4g}")


def to_b64(img01):
    u8 = np.rint(np.clip(img01, 0.0, 1.0) * 255.0).astype(np.uint8)
    return base64.b64encode(u8.reshape(-1).tobytes()).decode("ascii")


def js_list(values, per_line=20, indent="    "):
    vals = [str(v) for v in values]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return "[\n" + ",\n".join(indent + ln for ln in lines) + ",\n" + indent[:-2] + "]"


def js_num_list(values):
    return "[" + ", ".join(repr(sig4(v)) for v in values) + "]"


def header(lines):
    return "".join(f"// {ln}\n" if ln else "//\n" for ln in lines)


# ---------------------------------------------------------------- main -----
def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--data-dir", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--n-recon", type=int, default=10)
    ap.add_argument("--tsne-count", type=int, default=N_VALID)
    ap.add_argument("--skip-1by1", action="store_true")
    ap.add_argument("--gate-only", action="store_true")
    ap.add_argument("--date", default=dt.date.today().isoformat())
    args = ap.parse_args()
    if not 1 <= args.n_recon <= N_VALID or not 50 <= args.tsne_count <= N_VALID:
        sys.exit("--n-recon / --tsne-count out of range")

    import keras
    import sklearn
    from sklearn.manifold import TSNE

    versions = (f"Python {platform.python_version()}, TensorFlow {tf.__version__} "
                f"(tf.keras = Keras {keras.__version__}), NumPy {np.__version__}, "
                f"scikit-learn {sklearn.__version__}; CPU, {platform.system()}")
    print(versions)

    tf.config.experimental.enable_op_determinism()

    if args.gate_only:
        tf.keras.utils.set_random_seed(SEED)
        _, stacked_ae = build_stacked()
        gate("stacked_ae", stacked_ae)
        tf.keras.utils.set_random_seed(SEED)
        gate("tied_ae", build_tied())
        return

    hashes = fetch(args.data_dir)
    x_full_u8, y_full = load_fashion(args.data_dir)
    X_train_full = x_full_u8.astype(np.float32) / 255
    X_train, X_valid = X_train_full[:-N_VALID], X_train_full[-N_VALID:]
    y_valid = y_full[-N_VALID:]
    x_valid_u8 = x_full_u8[-N_VALID:]
    print(f"X_train {X_train.shape}  X_valid {X_valid.shape}")
    print("first 5 validation labels:", [CLASS_NAMES[i] for i in y_valid[:5]])

    training = {}
    recon = {}
    t0 = time.time()

    # ---- stacked_ae (slide 12)
    tf.keras.utils.set_random_seed(SEED)
    stacked_encoder, stacked_ae = build_stacked()
    p = gate("stacked_ae", stacked_ae)
    stacked_ae.compile(loss="mse", optimizer="nadam")
    history = stacked_ae.fit(X_train, X_train, epochs=20,
                             validation_data=(X_valid, X_valid), verbose=2)
    training["stacked"] = dict(params=p, epochs=20, h=history.history)
    recon["stacked"] = stacked_ae.predict(X_valid[:args.n_recon], verbose=0)

    # ---- tied_ae (slides 20-21)
    tf.keras.utils.set_random_seed(SEED)
    tied_ae = build_tied()
    p = gate("tied_ae", tied_ae)
    tied_ae.compile(loss="mse", optimizer="nadam")
    history = tied_ae.fit(X_train, X_train, epochs=10,
                          validation_data=(X_valid, X_valid), verbose=2)
    training["tied"] = dict(params=p, epochs=10, h=history.history)
    recon["tied"] = tied_ae.predict(X_valid[:args.n_recon], verbose=0)

    # ---- stacked_ae_1_by_1 (slides 23-25)
    if not args.skip_1by1:
        tf.keras.utils.set_random_seed(SEED)
        X_train_flat = tf.keras.layers.Flatten()(X_train)
        X_valid_flat = tf.keras.layers.Flatten()(X_valid)
        enc1, dec1, X_train_enc1, X_valid_enc1 = train_autoencoder(
            100, X_train_flat, X_valid_flat)
        enc2, dec2, _, _ = train_autoencoder(
            30, X_train_enc1, X_valid_enc1, output_activation="relu")
        stacked_ae_1_by_1 = tf.keras.Sequential([
            tf.keras.layers.Flatten(),
            enc1, enc2, dec2, dec1,
            tf.keras.layers.Reshape([28, 28])
        ])
        pre = stacked_ae_1_by_1.predict(X_valid, verbose=0)  # builds the model
        pre_mse = float(np.mean((pre - X_valid) ** 2))
        print(f"stacked_ae_1_by_1 valid MSE before fine-tuning: {pre_mse:.6f}")
        p = gate("stacked_ae_1_by_1", stacked_ae_1_by_1)
        stacked_ae_1_by_1.compile(loss="mse", optimizer="nadam")
        history = stacked_ae_1_by_1.fit(X_train, X_train, epochs=5,
                                        validation_data=(X_valid, X_valid),
                                        verbose=2)
        training["oneByOne"] = dict(params=p, epochs=5, h=history.history,
                                    phases=list(PHASE_HISTORIES), pre=pre_mse)
        recon["oneByOne"] = stacked_ae_1_by_1.predict(X_valid[:args.n_recon],
                                                      verbose=0)
    print(f"training wall time {time.time() - t0:.0f}s")

    # ---- t-SNE of the stacked_encoder codings (slide 14)
    t1 = time.time()
    X_valid_compressed = stacked_encoder.predict(X_valid[:args.tsne_count],
                                                 verbose=0)
    tsne = TSNE(init="pca", learning_rate="auto", random_state=SEED)
    X_valid_2D = tsne.fit_transform(X_valid_compressed)
    tsne_secs = time.time() - t1
    print(f"t-SNE on {X_valid_compressed.shape}: KL {tsne.kl_divergence_:.4f}, "
          f"{tsne.n_iter_} iterations, {tsne_secs:.0f}s")

    # ------------------------------------------------------------ export --
    models = list(recon)
    model_names = {"stacked": "stacked_ae (slide 12)",
                   "tied": "tied_ae (slides 20-21)",
                   "oneByOne": "stacked_ae_1_by_1 (slides 23-25)"}
    for k, h in training.items():
        print(f"{model_names[k]}: final train MSE {sig4(h['h']['loss'][-1])}, "
              f"valid MSE {sig4(h['h']['val_loss'][-1])}")

    common = [
        DISCLAIMER,
        "",
        "Source: Fashion MNIST (Xiao, Rasul & Vollgraf 2017), the IDX files at",
        f"  {BASE_URL}",
        "  (the files keras.datasets.fashion_mnist.load_data() downloads, parsed the same way)",
        f"  {FILES[1]} sha256 {hashes[FILES[1]]}",
        f"  {FILES[0]} sha256 {hashes[FILES[0]]}",
        f"Generated by {SCRIPT_PATH} on {args.date}.",
        "Split (Geron's): pixels / 255 as float32; X_train = first 55,000 training images,",
        "  X_valid = last 5,000 (training images 55000..59999). Test set unused.",
        f"Seeds: tf.keras.utils.set_random_seed({SEED}) before each model is built;",
        f"  op determinism on; TSNE random_state={SEED}.",
        f"Libraries: {versions}.",
        "Training: loss='mse', optimizer='nadam' (Keras defaults: batch 32, shuffle on).",
        "  stacked_ae 20 epochs (slide 12); tied_ae 10 epochs (slides 20-21)"
        + ("; stacked_ae_1_by_1" if "oneByOne" in training else "."),
    ]
    if "oneByOne" in training:
        common.append("  10 + 10 epochs one autoencoder at a time, then 5 fine-tuning (slides 24-25).")
    common.append("Do not edit by hand: re-run the script.")

    # recon.js
    items = []
    for i in range(args.n_recon):
        fields = [f"index: {i}", f"label: {int(y_valid[i])}",
                  f"original: '{base64.b64encode(x_valid_u8[i].reshape(-1).tobytes()).decode('ascii')}'"]
        for m in models:
            fields.append(f"{m}: '{to_b64(recon[m][i])}'")
        mse = ", ".join(f"{m}: {sig4(np.mean((recon[m][i] - X_valid[i]) ** 2))}"
                        for m in models)
        fields.append(f"mse: {{ {mse} }}")
        items.append("    {\n" + "".join(f"      {f},\n" for f in fields) + "    },\n")

    def train_block(k):
        t = training[k]
        h = t["h"]
        out = [f"  {k}: {{\n",
               f"    model: '{model_names[k].split(' ')[0]}',\n",
               f"    params: {t['params']},\n",
               f"    epochs: {t['epochs']},\n",
               f"    finalTrainMse: {sig4(h['loss'][-1])},\n",
               f"    finalValidMse: {sig4(h['val_loss'][-1])},\n",
               f"    loss: {js_num_list(h['loss'])},\n",
               f"    valLoss: {js_num_list(h['val_loss'])},\n"]
        if k == "oneByOne":
            ph = t["phases"]
            out += ["    // phase 1: 784-100-784 on pixels; phase 2: 100-30-100 on the phase-1 codings\n",
                    "    // (phase 2's MSE is in coding units, not pixels). loss/valLoss above = the 5 fine-tuning epochs.\n",
                    f"    phase1: {{ epochs: {len(ph[0]['loss'])}, loss: {js_num_list(ph[0]['loss'])}, valLoss: {js_num_list(ph[0]['val_loss'])} }},\n",
                    f"    phase2: {{ epochs: {len(ph[1]['loss'])}, loss: {js_num_list(ph[1]['loss'])}, valLoss: {js_num_list(ph[1]['val_loss'])} }},\n",
                    f"    validMseBeforeFineTune: {sig4(t['pre'])},\n"]
        out.append("  },\n")
        return "".join(out)

    recon_js = (
        "// Fashion MNIST reconstructions by the Lecture 5 autoencoders.\n"
        + header(common + [
            "",
            f"RECON.items[i] is X_valid[i] (training image {60000 - N_VALID} + i), i = 0..{args.n_recon - 1};",
            "  slide 13's grid shows the first 5. Images: base64 of 784 uint8 bytes, row-major",
            "  28x28, 0 = background, 255 = full intensity (the dataset's own values; slides'",
            "  cmap='binary' draws 255 as black). Reconstructions are the model output clipped",
            "  to [0,1] then rounded x*255. mse = that image's MSE on the unclipped output.",
            "TRAINING: finalTrainMse is Keras's logged 'loss' for the last epoch (mean over that",
            "  epoch's batches); finalValidMse is 'val_loss' (X_valid, end of the last epoch).",
            "  loss/valLoss are per epoch. All values rounded to 4 significant figures.",
            "Re-running the script on the same software stack reproduces this file byte for byte.",
        ])
        + "\n"
        + "export const RECON = {\n"
        + "  width: 28,\n  height: 28,\n"
        + "  encoding: 'base64-uint8',\n"
        + "  classNames: [" + ", ".join(f"'{c}'" for c in CLASS_NAMES) + "],\n"
        + f"  validStart: {60000 - N_VALID},\n"
        + "  models: [" + ", ".join(f"'{m}'" for m in models) + "],\n"
        + "  items: [\n" + "".join(items) + "  ],\n"
        + "}\n\n"
        + "export const TRAINING = {\n"
        + "".join(train_block(k) for k in training)
        + "}\n"
    )

    # tsne.js: one scale for both axes (keeps t-SNE's aspect ratio)
    lo = X_valid_2D.min(axis=0)
    span = X_valid_2D.max(axis=0) - lo
    scale = 1000.0 / float(span.max())
    xy = np.rint((X_valid_2D - lo) * scale).astype(int)
    extent = [int(xy[:, 0].max()), int(xy[:, 1].max())]
    tsne_js = (
        "// t-SNE of the stacked_ae encoder's 30-D codings of Fashion MNIST validation images.\n"
        + header(common + [
            "",
            f"Points: X_valid[0..{args.tsne_count - 1}] (training images {60000 - N_VALID}.."
            f"{60000 - N_VALID + args.tsne_count - 1}), count {args.tsne_count}.",
            "Slide 14's code: X_valid_compressed = stacked_encoder.predict(X_valid);",
            "  TSNE().fit_transform(X_valid_compressed). Run here as",
            f"  TSNE(init='pca', learning_rate='auto', random_state={SEED}) - the first two are",
            f"  scikit-learn {sklearn.__version__}'s defaults (as are perplexity={tsne.perplexity},"
            f" max_iter={tsne.max_iter});",
            f"  final KL divergence {tsne.kl_divergence_:.4f}.",
            "Coordinates: both axes shifted to start at 0 and multiplied by ONE factor so the",
            "  longer axis spans 0..1000 (aspect ratio kept); rounded to integers. x[i], y[i],",
            "  labels[i] are point i. y is t-SNE's own axis (matplotlib draws it upward; an SVG",
            "  that wants the same picture uses extent[1] - y). Axes have no meaning in t-SNE.",
        ])
        + "\n"
        + "export const TSNE = {\n"
        + f"  count: {args.tsne_count},\n"
        + f"  validStart: {60000 - N_VALID},\n"
        + f"  extent: [{extent[0]}, {extent[1]}],\n"
        + "  classNames: [" + ", ".join(f"'{c}'" for c in CLASS_NAMES) + "],\n"
        + f"  x: {js_list(xy[:, 0].tolist())},\n"
        + f"  y: {js_list(xy[:, 1].tolist())},\n"
        + f"  labels: {js_list([int(v) for v in y_valid[:args.tsne_count]], per_line=50)},\n"
        + "}\n"
    )

    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in (("recon.js", recon_js), ("tsne.js", tsne_js)):
        path = args.out / name
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}  {path.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
