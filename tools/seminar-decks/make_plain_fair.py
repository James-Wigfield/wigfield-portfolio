"""The plain deck's per-scan points for slide 11 (the comparison with PSMASegmentator).

Reads the two per-case result files of the fair comparison straight from Mamba_PSMA:
  evaluation/results/run4-vs-baseline-deeppsma/scored/baseline_per_case.csv
      PSMASegmentator 1.1.0 (threshold 0.5, min_voxels 10)
  evaluation/results/run4-deeppsma-external/checkpoint_best_val_threshold_sweep_per_case.csv
      the autoPET-only hybrid (threshold 0.5, min_voxels 10, expand False, split False)
Per-case F1 = 2TP / (2TP + FP + FN), compared as exact fractions of the integer counts,
as Mamba_PSMA/scripts/thesis_figures/plot_baseline_per_case.py does. Writes no case id.

Checks before writing (nothing is written if one fails):
  - the same 100 cases and the same n_gt in both files;
  - better / worse / tied = fair.better / fair.worse / fair.tied (48 / 50 / 2);
  - under 20 lesions: 22 scans, 18 lower; 100 or more: 28 scans, 23 higher;
  - pooled F1 of both models = fair.r4_f1 and fair.psm_f1;
  - the points equal public/seminar-decks/data/fair-per-case.json (the old decks' copy).

Writes: src/components/portal/modules/seminar-decks/decks/plain/fair.gen.js
Run (portfolio root): python -I tools/seminar-decks/make_plain_fair.py
"""
import csv
import json
import os
import sys
from fractions import Fraction

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MP = os.path.abspath(os.path.join(ROOT, '..', '..', 'university', 'cits4010', 'Mamba_PSMA'))
BASE = os.path.join(MP, 'evaluation', 'results', 'run4-vs-baseline-deeppsma', 'scored', 'baseline_per_case.csv')
MINE = os.path.join(MP, 'evaluation', 'results', 'run4-deeppsma-external', 'checkpoint_best_val_threshold_sweep_per_case.csv')
JSON = os.path.join(ROOT, 'public', 'seminar-decks', 'data', 'fair-per-case.json')
OUT = os.path.join(ROOT, 'src', 'components', 'portal', 'modules', 'seminar-decks', 'decks', 'plain', 'fair.gen.js')

EXPECT = {'n': 100, 'better': 48, 'worse': 50, 'tied': 2, 'lt20_n': 22, 'lt20_lower': 18, 'ge100_n': 28, 'ge100_higher': 23}


def load(path, keep):
    with open(path, newline='', encoding='utf-8') as f:
        return {r['case_id']: r for r in csv.DictReader(f) if keep(r)}


def f1(r):
    tp, fp, fn = int(r['tp']), int(r['fp']), int(r['fn'])
    d = 2 * tp + fp + fn
    return Fraction(2 * tp, d) if d else Fraction(0)


def pooled(rows):
    tp = sum(int(r['tp']) for r in rows)
    fp = sum(int(r['fp']) for r in rows)
    fn = sum(int(r['fn']) for r in rows)
    return 2 * tp / (2 * tp + fp + fn)


def main():
    base = load(BASE, lambda r: r['threshold'] == '0.5' and r['min_voxels'] == '10')
    mine = load(MINE, lambda r: r['threshold'] == '0.5' and r['min_voxels'] == '10' and r['expand'] == 'False' and r['split'] == 'False')
    if set(base) != set(mine) or len(base) != EXPECT['n']:
        sys.exit('case lists differ')
    pts = []
    for c in sorted(base):
        if base[c]['n_gt'] != mine[c]['n_gt']:
            sys.exit(f'{c}: n_gt differs')
        pts.append((int(mine[c]['n_gt']), f1(mine[c]) - f1(base[c])))
    got = {
        'n': len(pts),
        'better': sum(d > 0 for _, d in pts),
        'worse': sum(d < 0 for _, d in pts),
        'tied': sum(d == 0 for _, d in pts),
        'lt20_n': sum(n < 20 for n, _ in pts),
        'lt20_lower': sum(n < 20 and d < 0 for n, d in pts),
        'ge100_n': sum(n >= 100 for n, _ in pts),
        'ge100_higher': sum(n >= 100 and d > 0 for n, d in pts),
    }
    if got != EXPECT:
        sys.exit(f'checks differ: {got}')
    pm, pb = pooled(mine.values()), pooled(base.values())
    if round(pm * 100, 1) != 81.4 or round(pb * 100, 1) != 78.4:
        sys.exit(f'pooled F1 differs: {pm} {pb}')
    # Sorted by lesion count, then difference: the order the slide draws them in.
    out = sorted((n, round(float(d) * 100, 2)) for n, d in pts)
    with open(JSON, encoding='utf-8') as f:
        old = sorted(tuple(p) for p in json.load(f)['cases'])
    if [(n, round(d, 2)) for n, d in old] != out:
        sys.exit('fair-per-case.json differs from the recomputed points')
    body = ',\n  '.join(f'[{n}, {d}]' for n, d in out)
    js = (
        '// Generated by tools/seminar-decks/make_plain_fair.py; do not edit.\n'
        '// The autoPET-only hybrid minus PSMASegmentator, per-scan lesion F1 in points, on the 100\n'
        '// DEEP-PSMA scans (threshold 0.5, 10-voxel filter, any-overlap matcher): [lesions in the\n'
        '// scan, difference]. Exact fractions of the per-case counts; no case ids.\n'
        f'// Checks: {json.dumps(got)}\n'
        f'export const FAIR_POINTS = [\n  {body},\n];\n'
    )
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    print(json.dumps({'written': os.path.relpath(OUT, ROOT), **got, 'pooled_hybrid': round(pm * 100, 2), 'pooled_psm': round(pb * 100, 2)}))


if __name__ == '__main__':
    main()
