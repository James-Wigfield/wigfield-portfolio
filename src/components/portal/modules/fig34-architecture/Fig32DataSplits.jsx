/* ============================================================================
   FIG 3.2 · DATA SPLITS — three options for one print figure, and the cuts
   ----------------------------------------------------------------------------
   Figure 3.2 of the CITS4010 dissertation (fig:method-data-splits): how the 697
   studies were split. Three layouts (A partition tree, B proportional bars, C
   fold grid), each a TikZ file written and compiled by
   Mamba_PSMA/scripts/thesis_figures/data_splits/make_data_splits.py, which also
   derives every count from the split files. Shown on the same page as Figures
   3.3 and 4.7 (Fig34Architecture.jsx switches between them).

   Counts only, no case ids or images, so the assets are bundled (?url in
   ./data-splits-options.js). ./data-splits/data.json is generated by the
   dissertation repo's documents/temp/final-week/oct16/data-splits-figure/
   tools/build.py: the counts with their sources, the asserts, each option's
   build record, and the Data splits paragraph cut into pieces and cut slots for
   the red-pen card. Words, critic verdicts and scores: ./data-splits-options.js.

   Views: on the page (a mock A4 sheet: the trimmed paragraph, the figure and
   the draft caption in the cshonours text block), dissertation pages (the
   scratch build's pages 18 and 19 at 110 dpi), true size and zoom 2x; a
   greyscale toggle (pdftoppm -gray renders, not a CSS filter); a compare view.
   ========================================================================== */

const PAGE = { w: 210, h: 297, left: 36.3, top: 45.4, textW: 144.6, textH: 208.0 };
const pct = (mm, of) => `${(100 * mm) / of}%`;
const MODES = [
  { id: 'page', label: 'On the page' },
  { id: 'diss', label: 'Dissertation pages' },
  { id: 'true', label: 'True size' },
  { id: 'zoom', label: 'Zoom 2x' },
];
const PARA_VIEWS = [
  { id: 'current', label: 'Current' },
  { id: 'marked', label: 'With cuts' },
  { id: 'clean', label: 'Clean' },
];
const ALL_CUTS = DATA.cuts.map((c) => c.id);
// Printed page numbers of the paragraph and the figure in the scratch build (the
// spread is the paragraph's page, then the figure's).
const spreadPages = (id) => {
  const p = Number(DATA.options[id].printedPage);
  const b = DATA.options[id].build;
  const two = b.paragraph_pages?.[0] !== b.figure_pages?.[0];
  return two ? `${p - (b.figure_pages[0] - b.paragraph_pages[0])} and ${p}` : `${p}`;
};

// The paragraph as React nodes: 'current' (the base text), 'marked' (red pen for the
// selected cuts) or 'clean' (the selected cuts applied, no marks).
function paragraph(view, selected) {
  return DATA.pieces.map((p, i) => {
    if (p.text != null) return <span key={i}>{p.text}</span>;
    const on = selected.has(p.cut);
    if (view === 'current' || !on) return <span key={i}>{p.old}</span>;
    if (view === 'clean') return <span key={i}>{p.new}</span>;
    return (
      <span key={i}>
        {p.diff.map((d, j) => {
          const sp = j < p.diff.length - 1 ? ' ' : '';
          if (d.t === 'del') return <del key={j}>{d.s}{sp}</del>;
          if (d.t === 'ins') return <ins key={j}>{d.s}{sp}</ins>;
          return <span key={j}>{d.s}{sp}</span>;
        })}
        <sup>{p.cut}</sup>
      </span>
    );
  });
}

function Figure({ opt, mode, grey, selected }) {
  const a = ASSETS[opt.id];
  const info = DATA.options[opt.id];
  const alt = `Figure 3.2, option ${opt.id}: ${opt.name}`;
  const src = grey ? a.grey : a.svg;
  if (mode === 'page') {
    return (
      <div className="f34-sheet" role="img" aria-label={`${alt}, shown on an A4 page with the trimmed paragraph above it`}>
        <div
          className="f34-sheet__block"
          style={{ left: pct(PAGE.left, PAGE.w), top: pct(PAGE.top, PAGE.h), width: pct(PAGE.textW, PAGE.w) }}
        >
          <p className="f32-sheet__head"><span>{DATA.heading.split(' ')[0]}</span>{DATA.heading.split(' ').slice(1).join(' ')}</p>
          <p className="f32-sheet__para">{paragraph('clean', selected)}</p>
          <img src={src} alt="" className="f34-sheet__fig" />
          <p className="f34-sheet__cap">Figure 3.2: {info.caption}</p>
        </div>
        <span
          className="f34-sheet__frame"
          style={{
            left: pct(PAGE.left, PAGE.w), top: pct(PAGE.top, PAGE.h),
            width: pct(PAGE.textW, PAGE.w), height: pct(PAGE.textH, PAGE.h),
          }}
          aria-hidden="true"
        />
      </div>
    );
  }
  if (mode === 'diss') {
    return (
      <div className="f32-diss">
        <img
          src={grey ? a.spreadGrey : a.spread}
          alt={`${alt}: pages ${spreadPages(opt.id)} of a scratch build of the dissertation with this option and every cut in place`}
        />
      </div>
    );
  }
  const width = mode === 'zoom' ? `${2 * PAGE.textW}mm` : `${PAGE.textW}mm`;
  return (
    <div className="f34-scroll">
      <div className="f34-paper">
        <img src={src} alt={alt} style={{ width }} className="f34-paper__fig" />
      </div>
    </div>
  );
}

