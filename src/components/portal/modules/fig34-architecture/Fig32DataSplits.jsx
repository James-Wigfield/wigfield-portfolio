function Numbers({ sel }) {
  const rows = useMemo(() => {
    const keys = [];
    OPTIONS.forEach((o) => DATA.options[o.id].numbers.forEach((k) => { if (!keys.includes(k)) keys.push(k); }));
    return keys.map((k) => ({
      key: k,
      value: DATA.facts[k],
      label: LABELS[k] || k,
      source: DATA.sources[k] || '',
      in: Object.fromEntries(OPTIONS.map((o) => [o.id, DATA.options[o.id].numbers.filter((x) => x === k).length])),
    }));
  }, []);
  return (
    <section className="pt-card f32-card">
      <h3>Numbers</h3>
      <p className="f32-para">
        Every count in the three figures, with the split file it comes from and its key in{' '}
        <code>scripts/thesis_figures/data_splits/facts.json</code>. No count is typed into a <code>.tex</code> file:
        the script writes each one in. <code>verify_numbers.py</code> derives the counts again from the split files,
        extracts each compiled PDF’s text with <code>pdftotext</code> and checks that the integers in it are exactly the
        recorded counts plus the fold and run numbers. It passed on all three. The numbers in the chapter’s SOURCE
        comments all agreed with the files; none needed correcting.
      </p>
      <div className="f32-tablewrap">
        <table className="f32-table">
          <thead>
            <tr>
              <th>Count</th><th>What</th>
              {OPTIONS.map((o) => <th key={o.id}>{o.id}</th>)}
              <th>Source</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.key} className={r.in[sel] ? '' : 'is-off'}>
                <td className="f32-num">{r.value}</td>
                <td>{r.label}<br /><code>{r.key}</code></td>
                {OPTIONS.map((o) => (
                  <td key={o.id} className="f32-mark">
                    {r.in[o.id] ? <span className="f32-yes">{r.in[o.id] > 1 ? `✓ ×${r.in[o.id]}` : '✓'}</span> : <span className="f32-no">–</span>}
                  </td>
                ))}
                <td><code>{r.source}</code></td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="f32-note">Rows the selected option ({sel}) does not print are dimmed. ×n: printed n times.</p>
      <details className="f32-details">
        <summary>The {DATA.asserts.length} asserts that passed</summary>
        <ol>{DATA.asserts.map((s) => <li key={s}>{s}</li>)}</ol>
      </details>
    </section>
  );
}

function Cuts() {
  const [view, setView] = useState('marked');
  const [selected, setSelected] = useState(() => new Set(ALL_CUTS));
  const [comp, setComp] = useState(() => new Set(DATA.companions.map((c) => c.id)));
  const [copied, setCopied] = useState(false);
  const toggle = (set, setter, id) => setter(() => {
    const n = new Set(set);
    if (n.has(id)) n.delete(id); else n.add(id);
    return n;
  });
  const ids = useMemo(
    () => [...ALL_CUTS.filter((i) => selected.has(i)), ...DATA.companions.map((c) => c.id).filter((i) => comp.has(i))],
    [selected, comp],
  );
  const copy = useCallback(() => {
    navigator.clipboard?.writeText(`Figure 3.2 cuts chosen: ${ids.join(', ')}`)
      .then(() => { setCopied(true); setTimeout(() => setCopied(false), 1500); })
      .catch(() => { /* the ticked list stays on the page */ });
  }, [ids]);
  const saved = DATA.cuts.filter((c) => selected.has(c.id)).reduce((s, c) => s + c.words, 0);
  const w = DATA.words;
  return (
    <section className="pt-card f32-card">
      <h3>Suggested cuts to {DATA.heading}</h3>
      <p className="f32-para">
        Once the figure carries the numbers, the paragraph keeps only the reasoning: every split by patient, the
        sealed test set never trained on or used for selection, fold 0 built as run 4’s split plus DEEP-PSMA (so the
        comparison isolates DEEP-PSMA), the stratification of folds 1 to 4, and why unequal folds do not matter. Each
        cut applies on its own; untick any you want to keep. Base: <code>chapters/03-methodology.tex</code> at{' '}
        <code>{DATA.baseHead}</code>{DATA.baseDirty ? ' (working tree differs from HEAD)' : ', identical to HEAD'}.
        Nothing in the dissertation was edited.
      </p>
      <div className="f32-actions">
        <div className="f34-seg" role="group" aria-label="Paragraph view">
          {PARA_VIEWS.map((v) => (
            <button key={v.id} type="button" className={view === v.id ? 'is-active' : ''} aria-pressed={view === v.id}
              onClick={() => setView(v.id)}>
              {v.label}
            </button>
          ))}
        </div>
        <button type="button" className="f32-btn" onClick={copy} disabled={!ids.length} title="Copy the ticked IDs to the clipboard">
          {copied ? 'Copied' : 'Copy IDs'}
        </button>
        <span className="f32-note">{ids.length ? ids.join(', ') : 'nothing ticked'}</span>
      </div>
      <p className="f32-redpen">{paragraph(view, selected)}</p>
      <dl className="f32-stats">
        <div><dt>Paragraph words</dt><dd>{w.before} → {w.before + saved} ({saved})</dd></div>
        <div><dt>Caption words</dt><dd>now {DATA.captionCurrentWords}; A {DATA.options.A.captionWords}, B {DATA.options.B.captionWords}, C {DATA.options.C.captionWords}</dd></div>
        <div><dt>All-in, every cut + CE-01</dt><dd>{w.allinBase.toLocaleString('en-AU')} → A {DATA.options.A.allin.toLocaleString('en-AU')}, B {DATA.options.B.allin.toLocaleString('en-AU')}, C {DATA.options.C.allin.toLocaleString('en-AU')}</dd></div>
        <div><dt>Overlap with audit-and-cuts</dt><dd>{DATA.validation.audit_overlaps.length ? DATA.validation.audit_overlaps.join('; ') : `none (${DATA.validation.audit_checked} changes)`}</dd></div>
      </dl>
      <div className="f32-tablewrap">
        <table className="f32-table">
          <thead>
            <tr><th>Keep</th><th>Cut</th><th>Words</th><th>Why</th><th>Where the number now lives</th><th>Requires</th></tr>
          </thead>
          <tbody>
            {DATA.cuts.map((c) => (
              <tr key={c.id} className={selected.has(c.id) ? '' : 'is-off'}>
                <td>
                  <label className="f32-check">
                    <input type="checkbox" checked={selected.has(c.id)} onChange={() => toggle(selected, setSelected, c.id)} />
                    <span className="f32-cutrow-id">{c.id}</span>
                  </label>
                </td>
                <td>removes {c.removes.join(', ')}</td>
                <td className="f32-num">{c.words}</td>
                <td>{c.reason}</td>
                <td>{c.lives}</td>
                <td>{c.requires.length ? c.requires.join('; ') : '–'}{c.companions.length ? ` · with ${c.companions.join(', ')}` : ''}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <h4>Companion edits</h4>
      {DATA.companions.map((c) => (
        <div key={c.id} className="f32-para">
          <label className="f32-check">
            <input type="checkbox" checked={comp.has(c.id)} onChange={() => toggle(comp, setComp, c.id)} />
            <span className="f32-cutrow-id">{c.id}</span>
          </label>{' '}
          <code>{c.file}</code>: <code>{c.old}</code> → <code>{c.new}</code>. {c.reason}
        </div>
      ))}
      <p className="f32-note">
        Files to apply from: <code>data-splits-figure/suggested-cuts.json</code> (old and new LaTeX for each),{' '}
        <code>suggested-cuts.md</code>, and <code>paragraph-after.tex</code> (all six cuts, for a quick paste). The
        handover gives the steps.
      </p>
    </section>
  );
}

export default function Fig32DataSplits() {
  const [sel, setSel] = useState(CHOSEN || RECOMMENDATION.id);
  const [mode, setMode] = useState('page');
  const [grey, setGrey] = useState(false);
  const [compare, setCompare] = useState(false);
  const [pair, setPair] = useState(['A', 'B']);
  const byId = Object.fromEntries(OPTIONS.map((o) => [o.id, o]));
  const opt = byId[sel];
  // the mock page shows the paragraph as placed (no cuts) once an option is placed
  const all = useMemo(() => new Set(DATA.placed ? DATA.placed.cuts : ALL_CUTS), []);

  return (
    <div className="pt-module f34 f32">
      <header>
        <p className="f34-kicker">CITS4010 · dissertation · Chapter 3</p>
        <h2 className="f34-title">Figure 3.2: how the 697 studies were split</h2>
        <p className="pt-module__intro">
          Three designs of the same figure, each written by a script from the split files and compiled to the PDF that
          would print, and the cuts the Data splits paragraph can take once the figure carries its numbers. Pick an
          option and the cuts you want; the handover says how to place them.
        </p>
      </header>

      {DATA.placed && (
        <section className="f34-reco pt-card">
          <h3>Placed <span>({DATA.placed.date}, on {DATA.placed.baseHead})</span></h3>
          <p className="f34-reco__pick">
            Option {DATA.placed.option}: {byId[DATA.placed.option].name}, {DATA.placed.cuts.length ? `with ${DATA.placed.cuts.join(', ')}` : 'without the cuts'}
            {' '}(caption {DATA.placed.captionWords} words, {DATA.placed.allinDelta > 0 ? '+' : ''}{DATA.placed.allinDelta} all-in; pages {DATA.placed.pages})
          </p>
          <p className="f34-reco__note">{DATA.placed.note}</p>
        </section>
      )}

      <section className="f34-brief pt-card">
        <h3>The brief</h3>
        <ol>{BRIEF.points.map((p) => <li key={p}>{p}</li>)}</ol>
        <p className="f34-brief__rule">{BRIEF.rule}</p>
      </section>

      <div className="f34-bar" role="toolbar" aria-label="Figure options">
        <div className="f34-seg" role="group" aria-label="Option">
          {OPTIONS.map((o) => (
            <button key={o.id} type="button" className={!compare && sel === o.id ? 'is-active' : ''}
              aria-pressed={!compare && sel === o.id} onClick={() => { setSel(o.id); setCompare(false); }} title={o.name}>
              {o.id}
            </button>
          ))}
          <button type="button" className={compare ? 'is-active' : ''} aria-pressed={compare} onClick={() => setCompare(true)}>
            Compare
          </button>
        </div>
        {!compare && (
          <div className="f34-seg" role="group" aria-label="View">
            {MODES.map((m) => (
              <button key={m.id} type="button" className={mode === m.id ? 'is-active' : ''} aria-pressed={mode === m.id}
                onClick={() => setMode(m.id)}>
                {m.label}
              </button>
            ))}
          </div>
        )}
        <label className="f34-toggle">
          <input type="checkbox" checked={grey} onChange={(e) => setGrey(e.target.checked)} />
          Greyscale
        </label>
      </div>

      {compare ? (
        <section className="f34-compare">
          {[0, 1].map((i) => {
            const o = byId[pair[i]];
            return (
              <div key={i} className="f34-compare__col">
                <label className="f34-compare__pick">
                  <span>Option</span>
                  <select
                    value={pair[i]}
                    onChange={(e) => setPair((p) => (i === 0 ? [e.target.value, p[1]] : [p[0], e.target.value]))}
                  >
                    {OPTIONS.map((x) => <option key={x.id} value={x.id}>{x.id} · {x.name}</option>)}
                  </select>
                </label>
                <Figure opt={o} mode="page" grey={grey} selected={all} />
                <Scorecard opt={o} />
                <p className="f34-compare__concept">{o.concept}</p>
              </div>
            );
          })}
        </section>
      ) : (
        <>
          <p className="f34-caption-note">
            Option {opt.id} · {opt.name} · {MODES.find((m) => m.id === mode).label.toLowerCase()}
            {mode === 'page' && ' (the paragraph with every cut; the real build floats the figure to the next page)'}
            {mode === 'true' && ' (144.6 mm wide, as printed; depends on your screen reporting its size correctly)'}
            {mode === 'diss' && ` (pages ${spreadPages(opt.id)} of a scratch build with this option and every cut in place, 110 dpi)`}
          </p>
          <Figure opt={opt} mode={mode} grey={grey} selected={all} />
          <OptionDetail opt={opt} />
        </>
      )}

      <Cuts />
      <Numbers sel={sel} />

      <section className="f34-reco pt-card">
        <h3>Claude’s recommendation <span>(James decides)</span></h3>
        <p className="f34-reco__pick">Option {RECOMMENDATION.id}: {byId[RECOMMENDATION.id].name}</p>
        <ul>{RECOMMENDATION.reasons.map((r) => <li key={r}>{r}</li>)}</ul>
        {RECOMMENDATION.note && <p className="f34-reco__note">{RECOMMENDATION.note}</p>}
      </section>
    </div>
  );
}
