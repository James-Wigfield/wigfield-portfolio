/* ============================================================================
   DL PROJECT 2 — THE NOTEBOOK VIEW (lazy-loaded by ./Project2.jsx)
   ----------------------------------------------------------------------------
   The executed notebook, cell for cell in its own order (data/notebook.js is
   generated by tools/dl-project2/extract.mjs), set on "sheets", with the
   explainer plates breaking out between sections:

     header       title · Export PDF · the NotebookLM prompt dropdown under it
     chrome bar   sticky: filename tab, kernel, collapse-all, contents toggle
     rail         contents with scroll-spy (dropdown when narrow)
     flow         sheet → plates → sheet → … ; a plate renders after its
                  section's last cell, before the next heading
     print        a cover page, every cell expanded, stderr reduced to one
                  line, frozen storyboards; no rail, controls or prompt

   Deep links: /portal/dl-project-2/<section key> (title, s1 … s12,
   part-i, part-ii) scrolls to that section; the rail keeps the URL in step.
   ========================================================================== */

const WIDE_AT = 1080;
const plain = (s) => s.replace(/[`*_$]/g, '').replace(/\\/g, '');

// Contents entries in document order: each section's headings, then its plates.
function buildEntries() {
  const entries = [];
  const firstStart = SECTIONS[0]?.start ?? CELLS.length;
  const pushHeadings = (from, to) => {
    for (let i = from; i <= to; i++) {
      (CELLS[i].headings || []).forEach((h) => {
        if (h.level <= 3) entries.push({ kind: 'h', id: h.id, level: h.level, text: plain(h.text), cell: i });
      });
    }
  };
  pushHeadings(0, firstStart - 1);
  SECTIONS.forEach((s) => {
    pushHeadings(s.start, s.end);
    platesFor(s.key).forEach((p) => entries.push({ kind: 'plate', id: plateDomId(p.id), level: 3, text: p.title, no: p.no, section: s.key }));
  });
  return entries;
}

function useCopy() {
  const [copied, setCopied] = useState('');
  const timer = useRef(0);
  useEffect(() => () => window.clearTimeout(timer.current), []);
  const copy = useCallback(async (which, text, preEl) => {
    let ok = false;
    try {
      await navigator.clipboard.writeText(text);
      ok = true;
    } catch {
      // fallback: select the visible text so Ctrl+C works, and try execCommand
      if (preEl) {
        const range = document.createRange();
        range.selectNodeContents(preEl);
        const sel = window.getSelection();
        sel.removeAllRanges();
        sel.addRange(range);
        try {
          ok = document.execCommand('copy');
        } catch {
          ok = false;
        }
      }
    }
    setCopied(ok ? which : `${which}-selected`);
    window.clearTimeout(timer.current);
    timer.current = window.setTimeout(() => setCopied(''), 2200);
  }, []);
  return [copied, copy];
}

function NlmBlock({ which, label, hint, text, copied, onCopy }) {
  const preRef = useRef(null);
  const state = copied === which ? 'Copied' : copied === `${which}-selected` ? 'Selected — press Ctrl+C' : 'Copy';
  return (
    <div className="dlp2-nlm__block">
      <div className="dlp2-nlm__bar">
        <span className="dlp2-nlm__label">{label}</span>
        <span className="dlp2-nlm__hint">{hint}</span>
        <button type="button" className={`dlp2-btn dlp2-btn--sm${copied === which ? ' dlp2-btn--done' : ''}`} onClick={() => onCopy(which, text, preRef.current)}>
          {state}
        </button>
      </div>
      <pre className="dlp2-nlm__text" ref={preRef} tabIndex={0}>{text}</pre>
    </div>
  );
}

const fmtDate = (iso) => {
  try {
    return new Date(iso).toLocaleDateString('en-AU', { day: 'numeric', month: 'short', year: 'numeric' });
  } catch {
    return iso;
  }
};

export default function NotebookView() {
  const rootRef = useRef(null);
  const chromeRef = useRef(null);
  const dropRef = useRef(null);
  const { sub, setSub } = usePortalRoute();
  const entries = useMemo(buildEntries, []);
  const [collapsed, setCollapsed] = useState(loadCollapsed);
  const [railOpen, setRailOpen] = useState(() => load('rail', true) !== false);
  const [dropOpen, setDropOpen] = useState(false);
  const [nlmOpen, setNlmOpen] = useState(false);
  const [current, setCurrent] = useState(0);
  const [wide, setWide] = useState(true);
  const [stick, setStick] = useState(0);
  const [copied, copy] = useCopy();
  const live = useRef({ current: 0 });

  useEffect(() => { save('rail', railOpen); }, [railOpen]);
  useEffect(() => { save('collapsed', { in: [...collapsed.in], out: [...collapsed.out] }); }, [collapsed]);

  const onToggle = useCallback((which, i) => {
    setCollapsed((prev) => {
      const next = { in: new Set(prev.in), out: new Set(prev.out) };
      if (next[which].has(i)) next[which].delete(i);
      else next[which].add(i);
      return next;
    });
  }, []);
  const setAll = (which, shut) => {
    setCollapsed((prev) => ({ ...prev, [which]: shut ? new Set(CELLS.filter((c) => c.type === 'code' && (which === 'in' || c.outputs?.length)).map((c) => c.i)) : new Set() }));
  };

  // ── layout measurements ──────────────────────────────────────────────────
  useEffect(() => {
    const root = rootRef.current;
    if (!root || typeof ResizeObserver === 'undefined') return undefined;
    const ro = new ResizeObserver((es) => setWide(es[0].contentRect.width >= WIDE_AT));
    ro.observe(root);
    return () => ro.disconnect();
  }, []);
  useEffect(() => {
    const topbar = rootRef.current?.closest('.portal')?.querySelector('.portal__topbar');
    if (!topbar || typeof ResizeObserver === 'undefined') return undefined;
    const ro = new ResizeObserver(() => setStick(topbar.offsetHeight));
    ro.observe(topbar);
    return () => ro.disconnect();
  }, []);

  // ── scrolling ────────────────────────────────────────────────────────────
  const chromeBottom = useCallback(() => {
    const bar = chromeRef.current;
    if (!bar) return 0;
    return Math.max(bar.getBoundingClientRect().bottom, 0);
  }, []);

  const jumpTo = useCallback((id, { smooth = true } = {}) => {
    const el = document.getElementById(id);
    if (!el) return;
    const gap = chromeBottom() + 16;
    const dist = Math.abs(el.getBoundingClientRect().top - gap);
    const behavior = smooth && !prefersReducedMotion() && dist < window.innerHeight * 2.5 ? 'smooth' : 'instant';
    window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - gap, behavior });
    const focusable = el.matches('h1,h2,h3,h4,h5,h6,[tabindex]') ? el : el.querySelector('h1,h2,h3,h4,h5,h6,[tabindex="-1"]');
    focusable?.focus?.({ preventScroll: true });
    setDropOpen(false);
  }, [chromeBottom]);

  const onJump = useCallback((e) => {
    jumpTo(e.id);
    const sec = e.kind === 'plate' ? e.section : SECTIONS.filter((s) => s.start <= e.cell).pop()?.key;
    if (sec) setSub(sec, { replace: true });
  }, [jumpTo, setSub]);

  // deep link on arrival
  useEffect(() => {
    if (!sub) return undefined;
    const key = sub.split('/')[0];
    const plate = PLATES.find((p) => p.id === key);
    const sec = SECTIONS.find((s) => s.key === key);
    const id = plate ? plateDomId(plate.id) : sec ? sec.id : null;
    if (!id) return undefined;
    const t = window.setTimeout(() => jumpTo(id, { smooth: false }), 120);
    return () => window.clearTimeout(t);
    // only on arrival
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  // scroll-spy
  useEffect(() => {
    let raf = 0;
    const compute = () => {
      raf = 0;
      const top = chromeBottom();
      const line = top + (window.innerHeight - top) * 0.25;
      let idx = 0;
      for (let i = 0; i < entries.length; i++) {
        const el = document.getElementById(entries[i].id);
        if (el && el.getBoundingClientRect().top <= line) idx = i;
      }
      const sc = document.scrollingElement;
      if (sc && sc.scrollTop > 0 && sc.scrollTop + sc.clientHeight >= sc.scrollHeight - 4) idx = entries.length - 1;
      if (idx !== live.current.current) {
        live.current.current = idx;
        setCurrent(idx);
        save('last', entries[idx]?.id);
      }
    };
    const onScroll = () => {
      if (!raf) raf = requestAnimationFrame(compute);
    };
    window.addEventListener('scroll', onScroll, { passive: true });
    window.addEventListener('resize', onScroll, { passive: true });
    return () => {
      window.removeEventListener('scroll', onScroll);
      window.removeEventListener('resize', onScroll);
      if (raf) cancelAnimationFrame(raf);
    };
  }, [entries, chromeBottom]);

  // dropdown: Esc / click outside
  useEffect(() => {
    if (!dropOpen) return undefined;
    // Esc hands focus back to the Contents button rather than dropping it on <body>
    const onKey = (e) => {
      if (e.key !== 'Escape') return;
      setDropOpen(false);
      dropRef.current?.querySelector('button[aria-expanded]')?.focus();
    };
    const onDown = (e) => dropRef.current && !dropRef.current.contains(e.target) && setDropOpen(false);
    window.addEventListener('keydown', onKey);
    document.addEventListener('pointerdown', onDown);
    return () => {
      window.removeEventListener('keydown', onKey);
      document.removeEventListener('pointerdown', onDown);
    };
  }, [dropOpen]);

  // ── Export PDF: the browser's print pipeline + the PRINT block ──────────
  const exportPdf = () => {
    const prev = document.title;
    const restore = () => {
      document.title = prev;
      window.removeEventListener('afterprint', restore);
    };
    document.title = 'cits5017-project2-explainer';
    window.addEventListener('afterprint', restore);
    window.print();
  };

  const ctx = useMemo(() => ({ jumpTo }), [jumpTo]);
  const collapseTools = (
    <>
      <span className="dlp2-seg" role="group" aria-label="Code cells">
        <span className="dlp2-seg__k">code</span>
        <button type="button" onClick={() => setAll('in', true)}>hide</button>
        <button type="button" onClick={() => setAll('in', false)}>show</button>
      </span>
      <span className="dlp2-seg" role="group" aria-label="Outputs">
        <span className="dlp2-seg__k">outputs</span>
        <button type="button" onClick={() => setAll('out', true)}>hide</button>
        <button type="button" onClick={() => setAll('out', false)}>show</button>
      </span>
    </>
  );
  const titleCell = CELLS[0];
  const titleText = plain(titleCell?.headings?.[0]?.text || NB_META.filename);
  const showRail = wide && railOpen;
  const cur = entries[current];
  const curSection = cur ? (cur.kind === 'plate' ? entries.slice(0, current + 1).filter((e) => e.kind === 'h' && e.level <= 2).pop() : cur) : null;

  // the flow: sheets of cells, broken by each section's plates
  const flow = [];
  let sheet = [];
  const flush = (k) => {
    if (sheet.length) flow.push(<div className="dlp2-sheet" key={`sheet-${k}`}>{sheet}</div>);
    sheet = [];
  };
  const cellEl = (c) => (
    <Cell key={c.i} cell={c} inShut={collapsed.in.has(c.i)} outShut={collapsed.out.has(c.i)} onToggle={onToggle} />
  );
  const firstStart = SECTIONS[0]?.start ?? CELLS.length;
  CELLS.slice(0, firstStart).forEach((c) => sheet.push(cellEl(c)));
  SECTIONS.forEach((s) => {
    CELLS.slice(s.start, s.end + 1).forEach((c) => sheet.push(cellEl(c)));
    const plates = platesFor(s.key);
    if (plates.length) {
      flush(s.key);
      flow.push(
        <div className="dlp2-plates" key={`plates-${s.key}`} data-section={s.key}>
          {plates.map((p) => <p.Component key={p.id} meta={p} />)}
        </div>,
      );
    }
  });
  flush('end');

  return (
    <NbCtx.Provider value={ctx}>
      <div ref={rootRef} className="dl dlp2" style={{ '--dlp2-stick': `${stick}px` }}>
        <style>{PRINT_CSS}</style>
        {/* ── print-only cover ─────────────────────────────────────────── */}
        <section className="dlp2-cover">
          <p className="dlp2-cover__kicker">CITS5017 Deep Learning · UWA · Semester 2 2026 · Project 2</p>
          <h1 className="dlp2-cover__title">{titleText}</h1>
          <p className="dlp2-cover__what">
            An explained edition of James Wigfield’s executed notebook <b>{NB_META.filename}</b>: every cell in its original order —
            markdown, code and outputs, verbatim — with illustrated plates between the sections that explain what each part of the
            notebook did and why. Animated plates are frozen here as storyboard frames with their captions.
          </p>
          <p className="dlp2-cover__what">
            How to read the sources: “In [n]” marks a code cell and “Out [n]” the output printed under it; “cell k” is the notebook’s
            k-th cell (counting from 0). Numbers come from those outputs, or, for experiments that are not in the notebook, from the
            experiment log or the author’s handover, which the plates name. In a diagram marked “schematic” the drawing is an illustration; the numbers printed in it are real unless its schematic line says otherwise.
          </p>
          <dl className="dlp2-cover__meta">
            <div><dt>Author</dt><dd>James Wigfield</dd></div>
            <div><dt>Notebook</dt><dd>{NB_META.filename}</dd></div>
            <div><dt>Snapshot sha256</dt><dd>{NB_META.sha256}</dd></div>
            <div><dt>Extracted</dt><dd>{fmtDate(NB_META.extractedAt)}</dd></div>
            <div><dt>Jupyter kernel</dt><dd>{NB_META.kernel || '—'} (the kernel’s name; it runs TensorFlow 2.21.0)</dd></div>
            <div><dt>Cells</dt><dd>{NB_META.cells} ({NB_META.markdownCells} markdown, {NB_META.codeCells} code)</dd></div>
            <div><dt>Plates</dt><dd>{PLATES.length}</dd></div>
          </dl>
        </section>

        {/* ── header: title · Export PDF · NotebookLM ──────────────────── */}
        <header className="dlp2-head">
          <div className="dlp2-head__main">
            <p className="dlp2-head__kicker">CITS5017 · Deep Learning · Project 2</p>
            <h1 className="dlp2-head__title">The notebook, explained</h1>
            <p className="dlp2-head__lead">
              The executed notebook, cell for cell. Between its sections, plates{' '}
              <span className="dlp2-screen">animate</span>
              <span className="dlp2-print">show</span> what that part of the notebook did, with the real numbers and a receipt for each one.
            </p>
            <p className="dlp2-head__snap">
              snapshot <span title={NB_META.sha256}>sha256 {NB_META.sha12}</span> · {NB_META.filename} · extracted {fmtDate(NB_META.extractedAt)}
            </p>
          </div>
          <div className="dlp2-head__actions">
            <button type="button" className="dlp2-btn dlp2-btn--primary" onClick={exportPdf} title="Print this page to an A4 PDF: every cell expanded, plates frozen as storyboards">
              <svg viewBox="0 0 24 24" width="15" height="15" aria-hidden="true" focusable="false">
                <path d="M7 8V3.5h10V8M7 17H4.5V9.5h15V17H17M7 14h10v6.5H7z" fill="none" stroke="currentColor" strokeWidth="1.6" strokeLinejoin="round" />
              </svg>
              Export PDF
            </button>
            <button
              type="button"
              className="dlp2-btn"
              aria-expanded={nlmOpen}
              aria-controls="dlp2-nlm"
              onClick={() => setNlmOpen((v) => !v)}
            >
              <span className={`dlp2-chev${nlmOpen ? ' dlp2-chev--open' : ''}`} aria-hidden="true" />
              NotebookLM prompt
            </button>
          </div>
          <div className="dlp2-nlm" id="dlp2-nlm" hidden={!nlmOpen}>
            <p className="dlp2-nlm__note">{NLM_NOTE}</p>
            <NlmBlock which="full" label="Full prompt" hint={`${NLM_PROMPT.length} characters`} text={NLM_PROMPT} copied={copied} onCopy={copy} />
            <NlmBlock which="compact" label="Compact variant" hint={`${NLM_COMPACT.length} characters`} text={NLM_COMPACT} copied={copied} onCopy={copy} />
          </div>
        </header>

        {/* ── sticky notebook chrome ───────────────────────────────────── */}
        <div className="dlp2-chrome" ref={chromeRef}>
          <span className="dlp2-tab">
            <svg viewBox="0 0 16 16" width="13" height="13" aria-hidden="true" focusable="false">
              <path d="M4 1.8h5.5L12.5 5v9.2H4zM9.3 1.8V5.2h3.2" fill="none" stroke="currentColor" strokeWidth="1.3" strokeLinejoin="round" />
            </svg>
            <span className="dlp2-tab__name">{NB_META.filename}</span>
          </span>
          <span className="dlp2-kernel" title="The kernel the notebook was executed with">
            <span className="dlp2-kernel__dot" aria-hidden="true" />
            {NB_META.kernel || 'python3'}
          </span>
          <span className="dlp2-chrome__now" aria-live="polite">
            {curSection ? curSection.text : ''}
          </span>
          <span className="dlp2-chrome__tools">
            {wide && collapseTools}
            <span className="dlp2-drop-anchor" ref={dropRef}>
              {wide ? (
                !railOpen && (
                  <button type="button" className="dlp2-btn dlp2-btn--sm" onClick={() => setRailOpen(true)}>
                    Contents
                  </button>
                )
              ) : (
                <button type="button" className="dlp2-btn dlp2-btn--sm" aria-expanded={dropOpen} onClick={() => setDropOpen((v) => !v)}>
                  Contents
                </button>
              )}
              {!wide && dropOpen && (
                <div className="dlp2-drop">
                  <div className="dlp2-drop__tools">{collapseTools}</div>
                  <Toc entries={entries} current={current} onJump={onJump} variant="drop" />
                </div>
              )}
            </span>
          </span>
        </div>

        <dl className="dlp2-facts">
          <div>
            <dt>cells</dt>
            <dd>
              {NB_META.cells} · {NB_META.codeCells} code · {NB_META.executionCounts.sequential ? `In [${NB_META.executionCounts.first}]–[${NB_META.executionCounts.last}] in order` : 'execution counts out of order'}
            </dd>
          </div>
          {RUN_FACTS.map((f) => (
            <div key={f.k} title={f.src}>
              <dt>{f.k}</dt>
              <dd>
                {f.v}
                <span className="dlp2-print"> · {f.src}</span>
              </dd>
            </div>
          ))}
        </dl>

        <div className={`dlp2-layout${showRail ? ' dlp2-layout--rail' : ''}`}>
          {showRail && (
            <aside className="dlp2-rail">
              <Toc entries={entries} current={current} onJump={onJump} onClose={() => setRailOpen(false)} />
            </aside>
          )}
          <main className="dlp2-flow">
            {flow}
            <footer className="dlp2-end">
              <span>{NB_META.filename}</span>
              <span>sha256 {NB_META.sha12}</span>
              <span>extracted {fmtDate(NB_META.extractedAt)}</span>
              <span>{NB_META.cells} cells · {NB_META.codeCells} code · {NB_META.images} figures</span>
            </footer>
          </main>
        </div>
      </div>
    </NbCtx.Provider>
  );
}

