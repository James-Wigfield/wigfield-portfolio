import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { sfx } from './sfx';
import { getSettings, setSettings } from '../core/storage';
import { grade } from './grade.js';

export { grade };

/* ============================================================================
   GRADIENT ARCADE — THE ROUND ENGINE (every game runs on this)
   ----------------------------------------------------------------------------
   useRound({ gameId, seed, level, mode, durationMs, onRoundEnd, items })

   items: the round's questions, generated by the game from rng(seed) and
   level, each { id, concept, src, kind, prompt, answer, choices?, why,
   check?, tol?, beyond? }:
     kind     'number' | 'shape' (array of numbers) | 'choice' | 'custom'
     answer   the correct value (number · number[] · a choice value · any)
     check    optional (given) → boolean, used instead of equality
     why      one or two sentences in the slides' notation (the why card)
     src      { lecture, slides: [...] } — the receipt
   A game may instead pass `next(index, rand)` for items that depend on
   play; most pre-generate.

   State machine: intro → play → results.
     start()         play begins (the intro is marked seen for this game)
     submit(value)   grades, records { concept, correct, src }, scores,
                     shows feedback for FEEDBACK_MS, then advances; the last
                     item (or the timer at 0) ends the round
     skip()          counts as wrong
     finish()        ends early
   Scoring: a right answer is worth 10 + 2 × min(combo − 1, 5) points, so a
   run of six or more is worth 20 each; maxScore is a perfect run. Items not
   reached before the timer ends are not recorded (neither right nor wrong).

   onRoundEnd({ score, maxScore, outcomes }) fires exactly once; whatever
   it returns (the host's XP / best / boxes summary) is kept as `summary`
   for the results screen.

   DEV: window.__dla = { gameId, state(), current(), submit(), skip(),
   start(), finish(), items() } for the headless bot (never in production).
   ========================================================================== */

export const FEEDBACK_MS = 520;
export const pointsFor = (combo) => 10 + 2 * Math.min(Math.max(combo - 1, 0), 5);
export const perfectScore = (n) => Array.from({ length: n }, (_, i) => pointsFor(i + 1)).reduce((a, b) => a + b, 0);

export function useRound({ gameId, seed, level = 1, mode = 'free', durationMs = null, onRoundEnd, items: itemsIn, next = null, total: totalIn = null }) {
  const items = useMemo(() => itemsIn ?? [], [itemsIn]);
  const total = totalIn ?? items.length;
  const [state, setState] = useState('intro');
  const [index, setIndex] = useState(0);
  const [score, setScore] = useState(0);
  const [combo, setCombo] = useState(0);
  const [bestCombo, setBestCombo] = useState(0);
  const [feedback, setFeedback] = useState(null); // { correct, item, given }
  const [msLeft, setMsLeft] = useState(durationMs);
  const [summary, setSummary] = useState(null);
  const [dyn, setDyn] = useState(() => (next ? [next(0, null)] : [])); // items produced by next()
  const [outcomesState, setOutcomesState] = useState([]);
  const [mistakesState, setMistakesState] = useState([]);
  const outcomes = useRef([]); // the same lists, readable synchronously by finish()
  const mistakes = useRef([]);
  const ended = useRef(false);
  const startedAt = useRef(0);
  const feedbackTimer = useRef(0);
  const lastTick = useRef(0);

  const list = next ? dyn : items;
  const current = state === 'play' && !feedback ? list[index] ?? null : feedback?.item ?? list[index] ?? null;
  const maxScore = perfectScore(total);
  const introSeen = !!getSettings().introSeen?.[gameId];

  const finish = useCallback(() => {
    if (ended.current) return;
    ended.current = true;
    window.clearTimeout(feedbackTimer.current);
    const result = {
      score,
      maxScore,
      outcomes: outcomes.current.slice(),
      mistakes: mistakes.current.slice(),
      answered: outcomes.current.length,
      correct: outcomes.current.filter((o) => o.correct).length,
      bestCombo,
      elapsedMs: startedAt.current ? Date.now() - startedAt.current : 0,
      level,
      mode,
      seed,
      gameId,
    };
    let s = null;
    try {
      s = onRoundEnd?.(result) ?? null;
    } catch {
      s = null;
    }
    setSummary(s);
    setFeedback(null);
    setState('results');
    if (result.maxScore && result.score / result.maxScore >= 0.6) sfx.win();
    else sfx.flat();
  }, [score, maxScore, bestCombo, level, mode, seed, gameId, onRoundEnd]);

  const start = useCallback(() => {
    if (state !== 'intro') return;
    startedAt.current = Date.now();
    lastTick.current = Date.now();
    setState('play');
    setMsLeft(durationMs);
    sfx.start();
    try {
      const s = getSettings();
      if (!s.introSeen[gameId]) setSettings({ ...s, introSeen: { ...s.introSeen, [gameId]: true } });
    } catch {
      /* ignore */
    }
  }, [state, durationMs, gameId]);

  const advance = useCallback((fromIndex) => {
    setFeedback(null);
    const nextIndex = fromIndex + 1;
    if (nextIndex >= total) {
      finish();
      return;
    }
    if (next) setDyn((d) => (d.length > nextIndex ? d : [...d, next(nextIndex, outcomes.current[outcomes.current.length - 1] ?? null)]));
    setIndex(nextIndex);
  }, [total, finish, next]);

  const answer = useCallback((given, forcedWrong = false) => {
    if (state !== 'play' || feedback || ended.current) return null;
    const item = list[index];
    if (!item) return null;
    const correct = !forcedWrong && grade(item, given);
    const outcome = { concept: item.concept, correct, src: item.src, id: item.id };
    outcomes.current = [...outcomes.current, outcome];
    setOutcomesState(outcomes.current);
    let nextCombo = 0;
    if (correct) {
      nextCombo = combo + 1;
      setScore((s) => s + pointsFor(nextCombo));
      setCombo(nextCombo);
      setBestCombo((b) => Math.max(b, nextCombo));
      if (nextCombo >= 3 && nextCombo % 3 === 0) sfx.combo(nextCombo);
      else sfx.hit();
    } else {
      mistakes.current = [...mistakes.current, { item, given }];
      setMistakesState(mistakes.current);
      setCombo(0);
      sfx.miss();
    }
    setFeedback({ correct, item, given });
    window.clearTimeout(feedbackTimer.current);
    feedbackTimer.current = window.setTimeout(() => advance(index), FEEDBACK_MS);
    return { correct, item };
  }, [state, feedback, list, index, combo, advance]);

  const submit = useCallback((given) => answer(given, false), [answer]);
  const skip = useCallback(() => answer(null, true), [answer]);

  // the clock
  useEffect(() => {
    if (state !== 'play' || durationMs === null) return undefined;
    const id = window.setInterval(() => {
      const now = Date.now();
      const left = Math.max(0, durationMs - (now - startedAt.current));
      setMsLeft(left);
      if (left <= 5000 && left > 0 && now - lastTick.current >= 1000) {
        lastTick.current = now;
        sfx.tick();
      }
      if (left <= 0) finish();
    }, 100);
    return () => window.clearInterval(id);
  }, [state, durationMs, finish]);

  useEffect(() => () => window.clearTimeout(feedbackTimer.current), []);

  // the dev hook for the headless bot (the snapshot is refreshed after every render)
  const api = useRef(null);
  useEffect(() => {
    api.current = { state, current, submit, skip, start, finish, index, total, score, combo, feedback, items: list, msLeft };
  });
  useEffect(() => {
    if (!import.meta.env.DEV) return undefined;
    window.__dla = {
      gameId,
      seed,
      level,
      mode,
      state: () => api.current.state,
      current: () => api.current.current,
      items: () => api.current.items,
      index: () => api.current.index,
      total: () => api.current.total,
      score: () => api.current.score,
      feedback: () => api.current.feedback,
      msLeft: () => api.current.msLeft,
      start: () => api.current.start(),
      submit: (v) => api.current.submit(v),
      skip: () => api.current.skip(),
      finish: () => api.current.finish(),
    };
    return () => {
      if (window.__dla?.gameId === gameId) delete window.__dla;
    };
  }, [gameId, seed, level, mode]);

  return {
    state, index, total, score, maxScore, combo, bestCombo, msLeft, durationMs, feedback, summary, current, items: list,
    mistakes: mistakesState, outcomes: outcomesState, introSeen,
    start, submit, skip, finish,
    level, mode, seed, gameId,
  };
}
